number_user = int(input("Digite um número inteiro: ")) # Ebtrada de dados (inteiro)

sucessor = number_user + 1 # Sucessor (o número somado a + 1)
antecessor = number_user - 1 # Antecessor: (o número subtraído de - 1)

print (f"O número digite é: {number_user}") # Saída de dados formatada
print (f"O sucessor é: {sucessor}") # Saída de dados formatada
print (f"O antecessor é: {antecessor}") # Saída de dados formatada