number_value_1 = int(input("Digite um número para ser somado: ")) # Entrada de dados tipo primitivo inteiro
number_value_2 = int(input("Digite outro número: ")) # Entrada de dados tipo primitivo inteiro
soma_value = number_value_1 + number_value_2 # Variável soma usando o sinal de adição com as duas variáveis que o usuário digitou

print (f"A soma entre {number_value_1} e {number_value_2} é igual {soma_value}") # Formatação e exibição dos números digitados