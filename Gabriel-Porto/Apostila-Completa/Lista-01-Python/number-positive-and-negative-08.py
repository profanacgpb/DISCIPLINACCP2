number_user = int(input("Digite um número inteiro: ")) # Entrada de dados

# Condicionais múltiplas
if number_user > 0: # (+)
    print ("Número Positivo.") # Saída de dados
elif number_user < 0: # (-)
    print ("Número Negativo.") # Saída de dados
else: # Se não for nem um nem outro é esse:
    print ("O zero não é positivo nem negativo") # Saída de dados