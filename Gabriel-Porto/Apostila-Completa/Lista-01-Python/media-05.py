nota_1 = float(input("Digite sua primeira nota: ")) # Entrada de dados tipo float
nota_2 = float(input("Digite sua segunda nota: ")) # Entrada de dados tipo float

media = (nota_1 + nota_2) / 2 # Variável média, ordem de precedência

print (f"A sua primeira nota é: {nota_1}") # Saída de dados formatada
print (f"A sua segunda nota é: {nota_2}") # Saída de dados formatada
print (f"A sua média é: {media}") # Saída de dados formatada