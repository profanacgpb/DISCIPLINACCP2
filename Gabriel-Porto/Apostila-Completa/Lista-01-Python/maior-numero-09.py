number_1 = int(input("Digite um número inteiro: ")) # Entrada de dados
number_2 = int(input("Digite outro número inteiro: ")) # Entrada de dados

if number_1 > number_2: # Operadores matemáticos + Condicionais
    print (f"O primeiro número: {number_1} é maior") # Saída de dados
elif number_2 > number_1:
    print (f"O segundo número: {number_2} é maior") # Saída de dados
else:
    print (f"O primeiro número e o segundo número é igual") # Saída de dados