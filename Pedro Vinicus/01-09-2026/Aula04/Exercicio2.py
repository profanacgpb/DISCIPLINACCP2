#Exercicio 2 da aula 04 calcule notas de 50 cabem em um valor#

valor = int(input("Digite um valor: "))#Usuario digite o valor
notas_50 = valor // 50 #Variavel que calcula a quantidade de notas de 50 usando divisão inteira(//)
print("O número de notas de 50 que cabem no valor é:", notas_50) #Mostrando o resultado na tela