lista = [0, 1, 7, 2, 5, 8, 9, 6, 4]

# a. Retorne os primeiros 3 elementos da lista
print(lista[:3])

# b. Retorne os elementos da 3ª posição até a 7ª posição
print(lista[2:7])

# c. Retorne os elementos da lista de 3 em 3 elementos
print(lista[::3])

# d. Retorne os 3 últimos elementos da lista
print(lista[-3:])

# e. Retorne todos os elementos menos os 4 últimos
print(lista[:-4])