# Modele a participação de alunos em dois eventos e descubra quem participou dos dois, 
# de apenas um e de nenhum.

evento1 = {"João", "Maria", "Pedro", "Ana", "Carlos"}

evento2 = {"Maria", "Pedro", "Lucas", "Juliana", "Rafael"}

print(evento1 | evento2)
print(evento1 & evento2)
print(evento1 - evento2)
