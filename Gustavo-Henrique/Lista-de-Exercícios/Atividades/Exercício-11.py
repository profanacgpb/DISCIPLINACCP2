# contagem até 10
import time
for i in range(1,11):
    time.sleep(1)
    print(i)
    # O Programa automaticamente vai iniciar uma contagem até o 10
    # Utilizando o range ele começará do 1 até o 10 
    # A contagem tem um intervalo de 1 segundo
    # O programa mostra a sequência em formato de coluna