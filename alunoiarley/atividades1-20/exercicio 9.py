number_1 = int(input("Digite um número inteiro: ")) 
number_2 = int(input("Digite outro número inteiro: ")) 

if number_1 > number_2: 
    print (f"O primeiro número: {number_1} é maior") 
elif number_2 > number_1:
    print (f"O segundo número: {number_2} é maior") 
else:
    print (f"O primeiro número e o segundo número é igual") 