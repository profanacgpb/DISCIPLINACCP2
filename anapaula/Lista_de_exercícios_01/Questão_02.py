#QUESTÃO 02 - Soma de dois números

# Solicitação dos números ao usuário.
numero_1 = int(input('Digite o primeiro número inteiro: ')) #O primeiro número é armazenado na variável numero_1
numero_2 = int(input("Digite o segundo número inteiro: ")) #O segundo número é armazenado na variável numero_2

# Atribuição à variável soma a adição dos números informados pelo usuário.
soma = numero_1 + numero_2

# Pula uma linha e mostra o resultado na tela do usuário.
print(f'\nSoma = {soma}')